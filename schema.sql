-- Esquema de PostgreSQL para NEXUS Tech Market.
-- El backend puede crear estas tablas automáticamente con SQLAlchemy.

CREATE TABLE IF NOT EXISTS products (
    id VARCHAR(64) PRIMARY KEY,
    name VARCHAR(140) NOT NULL,
    category VARCHAR(50) NOT NULL,
    tag VARCHAR(40) NOT NULL,
    description VARCHAR(240) NOT NULL,
    price INTEGER NOT NULL CHECK (price >= 0),
    glyph VARCHAR(12) NOT NULL
);

CREATE TABLE IF NOT EXISTS purchase_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number VARCHAR(32) NOT NULL UNIQUE,
    customer_name VARCHAR(100) NOT NULL,
    customer_email VARCHAR(254) NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('pendiente', 'aprobada', 'rechazada')),
    total BIGINT NOT NULL CHECK (total >= 0),
    decision_note VARCHAR(250) NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    decided_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS purchase_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES purchase_requests(id) ON DELETE CASCADE,
    product_id VARCHAR(64) NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    product_name VARCHAR(140) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 10),
    unit_price INTEGER NOT NULL CHECK (unit_price >= 0)
);

CREATE INDEX IF NOT EXISTS purchase_requests_created_at_idx
    ON purchase_requests (created_at DESC);
